create or replace function public.habit_streaks(
  p_user_id uuid,
  p_today date
)
returns table (current_streak integer, longest_streak integer)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_cursor date;
  v_date date;
  v_previous date;
  v_run integer := 0;
begin
  if p_user_id is null or p_today is null then
    return query select 0, 0;
    return;
  end if;

  if exists (
    select 1 from public.entries
    where user_id = p_user_id and entry_date = p_today and word_count >= 100
  ) then
    v_cursor := p_today;
  else
    v_cursor := p_today - 1;
  end if;

  current_streak := 0;
  while exists (
    select 1 from public.entries
    where user_id = p_user_id and entry_date = v_cursor and word_count >= 100
  ) loop
    current_streak := current_streak + 1;
    v_cursor := v_cursor - 1;
  end loop;

  longest_streak := 0;
  for v_date in
    select entry_date
    from public.entries
    where user_id = p_user_id and word_count >= 100
    order by entry_date
  loop
    if v_previous is not null and v_date = v_previous + 1 then
      v_run := v_run + 1;
    else
      v_run := 1;
    end if;
    longest_streak := greatest(longest_streak, v_run);
    v_previous := v_date;
  end loop;

  return next;
end;
$$;

create or replace function public.set_habit_preferences(
  p_daily_prompts_enabled boolean,
  p_weekly_review_enabled boolean,
  p_weekly_review_day smallint,
  p_weekly_review_time time without time zone,
  p_habit_onboarding_completed boolean
)
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_profile public.profiles;
begin
  if v_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  if p_daily_prompts_enabled is null
    or p_weekly_review_enabled is null
    or p_habit_onboarding_completed is null
    or p_weekly_review_day not between 1 and 7
    or p_weekly_review_time is null then
    raise exception 'Valid habit preferences are required' using errcode = '22023';
  end if;

  update public.profiles
  set daily_prompts_enabled = p_daily_prompts_enabled,
      weekly_review_enabled = p_weekly_review_enabled,
      weekly_review_day = p_weekly_review_day,
      weekly_review_time = p_weekly_review_time,
      habit_onboarding_completed = p_habit_onboarding_completed,
      updated_at = now()
  where user_id = v_user_id
  returning * into v_profile;

  if not found then
    raise exception 'Profile required' using errcode = 'P0002';
  end if;

  return v_profile;
end;
$$;

create or replace function public.mark_welcome_back(p_entry_date date)
returns date
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_today date;
begin
  if v_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  select (now() at time zone timezone)::date
  into v_today
  from public.profiles
  where user_id = v_user_id;

  if v_today is null or p_entry_date is distinct from v_today then
    raise exception 'Welcome-back date must be today' using errcode = '22023';
