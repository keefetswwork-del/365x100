create or replace function public.record_media_event(
  p_event_name text,
  p_operation_id uuid,
  p_entry_date date default null,
  p_size_bucket text default null,
  p_duration_bucket text default null,
  p_failure_category text default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_tier text;
  v_inserted bigint;
begin
  if v_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if p_event_name not in (
    'photo_selected', 'photo_processing_completed', 'photo_processing_failed',
    'photo_upload_completed', 'photo_upload_failed', 'photo_replaced',
    'photo_removed', 'free_photo_limit_reached'
  ) then
    raise exception 'Unknown media event' using errcode = '22023';
  end if;
  if (select count(*) from public.media_events where user_id = v_user_id and occurred_at >= now() - interval '1 hour') >= 50 then
    return false;
  end if;

  v_tier := public.current_media_tier(v_user_id);
  insert into public.media_events (
    user_id, entry_date, event_name, operation_id, size_bucket,
    duration_bucket, failure_category, entitlement, dedupe_key
  ) values (
    v_user_id, p_entry_date, p_event_name, p_operation_id, p_size_bucket,
    p_duration_bucket, p_failure_category, v_tier,
    p_event_name || ':' || v_user_id::text || ':' || p_operation_id::text
  ) on conflict (dedupe_key) do nothing
  returning id into v_inserted;

  return v_inserted is not null;
end;
$$;

create or replace function public.get_entry_history(
  p_query text default null,
  p_from_date date default null,
  p_to_date date default null,
  p_before_date date default null,
  p_limit integer default 30
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_query text := nullif(btrim(p_query), '');
  v_items jsonb := '[]'::jsonb;
  v_has_more boolean := false;
  v_next_cursor date;
begin
  if v_user_id is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  if v_query is not null and char_length(v_query) > 200 then raise exception 'Search query is too long' using errcode = '22023'; end if;
  if p_limit is null or p_limit < 1 or p_limit > 50 then raise exception 'History page size must be between 1 and 50' using errcode = '22023'; end if;
  if p_from_date is not null and p_to_date is not null and p_from_date > p_to_date then raise exception 'History date range is invalid' using errcode = '22023'; end if;

  with candidates as (
    select e.entry_date, e.word_count, e.updated_at, e.word_count >= 100 as completed,
      regexp_replace(e.content, E'[\n\r\t ]+', ' ', 'g') as normalized_content,
      m.id as media_id, m.storage_path, m.byte_size, m.width, m.height,
      m.version as media_version, m.created_at as media_created_at, m.updated_at as media_updated_at
    from public.entries e
    left join public.entry_media m on m.entry_id = e.id
    where e.user_id = v_user_id
      and (p_from_date is null or e.entry_date >= p_from_date)
      and (p_to_date is null or e.entry_date <= p_to_date)
      and (p_before_date is null or e.entry_date < p_before_date)
      and (v_query is null or strpos(lower(e.content), lower(v_query)) > 0)
    order by e.entry_date desc limit p_limit + 1
  ), ranked as (
    select c.*, row_number() over (order by c.entry_date desc) as row_number from candidates c
  ), page as (
    select r.*,
      case
        when r.normalized_content = '' and r.media_id is not null then 'Photo saved; no words yet.'
        when v_query is null then left(r.normalized_content, 180)
        else substring(r.normalized_content from greatest(strpos(lower(r.normalized_content), lower(v_query)) - 80, 1) for 240)
      end as excerpt
    from ranked r where r.row_number <= p_limit
  )
  select coalesce(jsonb_agg(jsonb_build_object(
      'entryDate', p.entry_date, 'excerpt', p.excerpt, 'wordCount', p.word_count,
      'completed', p.completed, 'updatedAt', p.updated_at,
      'media', case when p.media_id is null then null else jsonb_build_object(
        'id', p.media_id, 'storagePath', p.storage_path, 'mimeType', 'image/webp',
        'byteSize', p.byte_size, 'width', p.width, 'height', p.height,
        'version', p.media_version, 'createdAt', p.media_created_at, 'updatedAt', p.media_updated_at
      ) end
    ) order by p.entry_date desc), '[]'::jsonb),
    (select count(*) > p_limit from candidates), min(p.entry_date)
  into v_items, v_has_more, v_next_cursor from page p;

  return jsonb_build_object('items', v_items, 'hasMore', v_has_more,
    'nextCursor', case when v_has_more then v_next_cursor else null end);
end;
$$;

create or replace function public.get_habit_dashboard(p_month date default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid(); v_profile public.profiles; v_today date;
  v_month_start date; v_month_end date; v_current_month_start date; v_year_start date;
  v_current_streak integer := 0; v_longest_streak integer := 0; v_first_entry date;
  v_last_completed date; v_last_writing date; v_total_words bigint := 0;
  v_total_completed integer := 0; v_total_writing integer := 0; v_last_seven_writing integer := 0;
  v_month_words bigint := 0; v_month_completed integer := 0; v_month_writing integer := 0;
  v_year_words bigint := 0; v_year_completed integer := 0; v_year_writing integer := 0;
  v_calendar jsonb := '[]'::jsonb;
begin
  if v_user_id is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  select * into v_profile from public.profiles where user_id = v_user_id;
  if not found then raise exception 'Profile required' using errcode = 'P0002'; end if;
  v_today := (now() at time zone v_profile.timezone)::date;
  v_month_start := date_trunc('month', coalesce(p_month, v_today))::date;
  v_month_end := (v_month_start + interval '1 month - 1 day')::date;
  v_current_month_start := date_trunc('month', v_today)::date;
  v_year_start := date_trunc('year', v_today)::date;
  select current_streak, longest_streak into v_current_streak, v_longest_streak from public.habit_streaks(v_user_id, v_today);
  select min(entry_date), max(entry_date) filter (where word_count >= 100),
    max(entry_date) filter (where public.entry_has_visible_content(content)), coalesce(sum(word_count), 0),
    count(*) filter (where word_count >= 100), count(*) filter (where public.entry_has_visible_content(content))
  into v_first_entry, v_last_completed, v_last_writing, v_total_words, v_total_completed, v_total_writing
  from public.entries where user_id = v_user_id;
  select count(*) filter (where public.entry_has_visible_content(content)) into v_last_seven_writing
  from public.entries where user_id = v_user_id and entry_date between v_today - 6 and v_today;
  select coalesce(sum(word_count), 0), count(*) filter (where word_count >= 100),
    count(*) filter (where public.entry_has_visible_content(content))
  into v_month_words, v_month_completed, v_month_writing from public.entries
  where user_id = v_user_id and entry_date between v_current_month_start and v_today;
  select coalesce(sum(word_count), 0), count(*) filter (where word_count >= 100),
    count(*) filter (where public.entry_has_visible_content(content))
  into v_year_words, v_year_completed, v_year_writing from public.entries
  where user_id = v_user_id and entry_date between v_year_start and v_today;
  select coalesce(jsonb_agg(jsonb_build_object(
    'entryDate', e.entry_date, 'wordCount', e.word_count, 'completed', e.word_count >= 100,
    'hasWriting', public.entry_has_visible_content(e.content),
    'hasPhoto', exists(select 1 from public.entry_media m where m.entry_id = e.id)
  ) order by e.entry_date), '[]'::jsonb) into v_calendar
  from public.entries e where e.user_id = v_user_id and e.entry_date between v_month_start and v_month_end;
  return jsonb_build_object(
    'today', v_today, 'visibleMonth', v_month_start, 'currentStreak', v_current_streak,
    'longestStreak', v_longest_streak, 'firstEntryDate', v_first_entry, 'lastCompletedDate', v_last_completed,
    'missedDays', case when v_last_completed is null then 0 else greatest(v_today - v_last_completed - 1, 0) end,
    'lastWelcomeBackDate', v_profile.last_welcome_back_date, 'totalWords', v_total_words,
    'totalCompletedDays', v_total_completed, 'monthWords', v_month_words,
    'monthCompletedDays', v_month_completed, 'monthElapsedDays', extract(day from v_today)::integer,
    'yearWords', v_year_words, 'yearCompletedDays', v_year_completed,
    'yearElapsedDays', extract(doy from v_today)::integer, 'calendar', v_calendar,
    'totalWritingDays', v_total_writing, 'lastSevenWritingDays', v_last_seven_writing,
    'monthWritingDays', v_month_writing, 'yearWritingDays', v_year_writing,
    'mostRecentWritingDate', v_last_writing,
    'daysSinceLastWriting', case when v_last_writing is null then 0 else greatest(v_today - v_last_writing, 0) end,
    'monthlyChapterEligible', v_month_writing >= 10,
    'monthlyChapterDaysRemaining', greatest(10 - v_month_writing, 0)
  );
end;
$$;

create or replace function public.media_cleanup_candidates(p_limit integer default 100)
returns table (storage_path text, attempts integer)
language sql
security definer
set search_path = ''
as $$
  select q.storage_path, q.attempts
  from public.media_cleanup_queue q
  where q.next_attempt_at <= now()
  order by q.next_attempt_at, q.id
  limit least(greatest(p_limit, 1), 500);
$$;

create or replace function public.orphaned_media_objects(p_limit integer default 100)
returns table (storage_path text)
language sql
security definer
set search_path = ''
as $$
  select o.name
  from storage.objects o
  left join public.entry_media m on m.storage_path = o.name
  where o.bucket_id = 'journal-media'
    and m.id is null
    and o.created_at < now() - interval '1 hour'
  order by o.created_at
  limit least(greatest(p_limit, 1), 500);
$$;

create or replace function public.user_media_storage_paths(p_user_id uuid)
returns table (storage_path text)
language sql
security definer
set search_path = ''
as $$
  select o.name
  from storage.objects o
  where o.bucket_id = 'journal-media'
    and (storage.foldername(o.name))[1] = p_user_id::text;
$$;

