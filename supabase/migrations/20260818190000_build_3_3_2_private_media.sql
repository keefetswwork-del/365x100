create or replace function public.get_media_account_status()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_tier text;
  v_count integer;
  v_privacy_version text;
  v_accepted boolean;
begin
  if v_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  v_tier := public.current_media_tier(v_user_id);
  select count(*) into v_count from public.entry_media where user_id = v_user_id;
  select version into v_privacy_version
  from public.legal_document_versions
  where document_type = 'privacy' and is_current;
  select exists (
    select 1 from public.legal_acceptances
    where user_id = v_user_id
      and document_type = 'privacy'
      and version = v_privacy_version
  ) into v_accepted;

  return jsonb_build_object(
    'tier', v_tier,
    'storedCount', v_count,
    'limit', case when v_tier = 'free' then 10 else null end,
    'canAdd', v_tier = 'premium' or v_count < 10,
    'privacyAccepted', v_accepted,
    'privacyVersion', v_privacy_version
  );
end;
$$;

