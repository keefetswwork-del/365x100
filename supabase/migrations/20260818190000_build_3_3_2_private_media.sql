create or replace function public.commit_entry_media(
  p_user_id uuid,
  p_entry_id uuid,
  p_media_id uuid,
  p_storage_path text,
  p_byte_size integer,
  p_width integer,
  p_height integer,
  p_operation_id uuid,
  p_expected_media_id uuid default null,
  p_expected_version bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_existing public.entry_media;
  v_saved public.entry_media;
  v_tier text;
  v_count integer;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));

  if not exists (
    select 1 from public.entries
    where id = p_entry_id and user_id = p_user_id
  ) then
    raise exception 'Entry not found' using errcode = 'P0002';
  end if;

  if p_storage_path <> p_user_id::text || '/' || p_entry_id::text || '/' || p_media_id::text || '.webp'
    or p_byte_size < 1 or p_byte_size > 1000000
    or p_width < 1 or p_width > 2500
    or p_height < 1 or p_height > 2500 then
    raise exception 'Invalid media metadata' using errcode = '22023';
  end if;

  select * into v_saved from public.entry_media where operation_id = p_operation_id;
  if found then
    if v_saved.user_id <> p_user_id or v_saved.entry_id <> p_entry_id then
      raise exception 'Invalid media operation' using errcode = '22023';
    end if;
    return jsonb_build_object('status', 'saved', 'media', to_jsonb(v_saved), 'oldPath', null);
  end if;

  select * into v_existing from public.entry_media where entry_id = p_entry_id for update;
  if found then
    if p_expected_media_id is null
      or p_expected_media_id <> v_existing.id
      or p_expected_version is null
      or p_expected_version <> v_existing.version then
      return jsonb_build_object('status', 'conflict', 'remote', to_jsonb(v_existing));
    end if;

    insert into public.media_cleanup_queue (user_id, storage_path, reason)
    values (p_user_id, v_existing.storage_path, 'replaced')
    on conflict (storage_path) do update
    set next_attempt_at = now(), updated_at = now();

    update public.entry_media
    set id = p_media_id,
        storage_path = p_storage_path,
        byte_size = p_byte_size,
        width = p_width,
        height = p_height,
        version = version + 1,
        operation_id = p_operation_id,
        updated_at = now()
    where entry_id = p_entry_id
    returning * into v_saved;

    return jsonb_build_object('status', 'saved', 'media', to_jsonb(v_saved), 'oldPath', v_existing.storage_path);
  end if;

  if p_expected_media_id is not null or p_expected_version is not null then
    return jsonb_build_object('status', 'conflict', 'remote', null);
  end if;

  v_tier := public.current_media_tier(p_user_id);
  select count(*) into v_count from public.entry_media where user_id = p_user_id;
  if v_tier = 'free' and v_count >= 10 then
    return jsonb_build_object('status', 'limit', 'storedCount', v_count, 'limit', 10);
  end if;

  insert into public.entry_media (
    id, user_id, entry_id, storage_path, byte_size, width, height, operation_id
  ) values (
    p_media_id, p_user_id, p_entry_id, p_storage_path, p_byte_size, p_width, p_height, p_operation_id
  ) returning * into v_saved;

  return jsonb_build_object('status', 'saved', 'media', to_jsonb(v_saved), 'oldPath', null);
end;
$$;

create or replace function public.remove_entry_media(
  p_user_id uuid,
  p_media_id uuid,
  p_expected_version bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_existing public.entry_media;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));
  select * into v_existing
  from public.entry_media
  where id = p_media_id and user_id = p_user_id
  for update;

  if not found then
    return jsonb_build_object('status', 'missing');
  end if;
  if v_existing.version <> p_expected_version then
    return jsonb_build_object('status', 'conflict', 'remote', to_jsonb(v_existing));
  end if;

  delete from public.entry_media where id = p_media_id;
  return jsonb_build_object('status', 'removed', 'storagePath', v_existing.storage_path);
end;
$$;

